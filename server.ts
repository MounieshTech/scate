import express from 'express';
import { createServer as createViteServer } from 'vite';
import { exec } from 'node:child_process';
import { promisify } from 'node:util';
import path from 'node:path';
import fs from 'node:fs';

const execAsync = promisify(exec);

async function startServer() {
  const app = express();
  const PORT = 3000;

  app.use(express.json());

  // API endpoint to execute scate CLI commands in real time
  app.post('/api/run', async (req, res) => {
    const rawCommand = (req.body.command || 'scate').trim();

    try {
      let cmdToRun = rawCommand;
      const binPath = path.resolve(process.cwd(), 'bin/scate.js');

      if (rawCommand.startsWith('scate')) {
        cmdToRun = `node "${binPath}" ${rawCommand.slice(5).trim()}`;
      } else if (rawCommand.startsWith('./bin/scate.js')) {
        cmdToRun = `node "${binPath}" ${rawCommand.slice(14).trim()}`;
      } else if (rawCommand === 'npm test') {
        cmdToRun = 'npx tsx --test test/scate.test.ts';
      } else {
        cmdToRun = `node "${binPath}"`;
      }

      const { stdout, stderr } = await execAsync(cmdToRun, {
        cwd: process.cwd(),
        env: { ...process.env, FORCE_COLOR: '1' },
      });

      res.json({
        success: true,
        command: rawCommand,
        output: stdout || stderr || '(No output returned)',
      });
    } catch (err: unknown) {
      const error = err as { stdout?: string; stderr?: string; message: string };
      res.json({
        success: false,
        command: rawCommand,
        output: error.stdout || error.stderr || error.message,
      });
    }
  });

  // API endpoint for simulating/testing AI Issue Resolver with Gemini
  app.post('/api/solve-issue', async (req, res) => {
    const { title, description } = req.body;
    if (!title) {
      return res.status(400).json({ error: 'Issue title is required' });
    }

    try {
      const { solveIssue } = await import('./scripts/ai-issue-fixer.js');
      const result = await solveIssue(title, description || '');
      res.json(result);
    } catch (err: unknown) {
      const error = err as Error;
      res.status(500).json({ success: false, error: error.message });
    }
  });

  // API endpoint to read a file generated by --o flag
  app.get('/api/file', async (req, res) => {
    const filePath = String(req.query.path || '');
    if (!filePath || filePath.includes('..')) {
      return res.status(400).json({ error: 'Invalid path' });
    }
    const fullPath = path.resolve(process.cwd(), filePath);
    if (!fs.existsSync(fullPath)) {
      return res.status(404).json({ error: 'File not found' });
    }
    try {
      const content = await fs.promises.readFile(fullPath, 'utf8');
      res.send(content);
    } catch {
      res.status(500).json({ error: 'Failed to read file' });
    }
  });

  // Mount Vite development server middlewares
  const isProduction = process.env.NODE_ENV === 'production';
  if (!isProduction) {
    const vite = await createViteServer({
      server: { middlewareMode: true, host: '0.0.0.0', port: PORT },
      appType: 'spa',
    });
    app.use(vite.middlewares);
  } else {
    app.use(express.static(path.resolve(process.cwd(), 'dist')));
    app.get('*', (_req, res) => {
      res.sendFile(path.resolve(process.cwd(), 'dist/index.html'));
    });
  }

  app.listen(PORT, '0.0.0.0', () => {
    console.log(`Server listening on http://0.0.0.0:${PORT}`);
  });
}

startServer();
